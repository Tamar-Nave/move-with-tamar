-- פשטידת גבינות וחלבון
update public.recipe_ingredients i set substitutes = v.subs
from public.recipes r,
  (values
    (1,  array['קמח לבן רגיל (אותה כמות)', 'קמח כוסמין לבן', 'שיבולת שועל טחונה דק', 'קמח ללא גלוטן']),
    (2,  array['1.5 כוסות קמח כוסמין מלא (אפשר רק כוסמין)', 'קמח לבן רגיל (אותה כמות)', 'שיבולת שועל טחונה דק']),
    (3,  array['½ כפית סודה לשתייה + 1 כף מיץ לימון']),
    (5,  array['8 חלבונים (יותר חלבון, פחות שומן)', '2 ביצים + 4 חלבונים']),
    (6,  array['חלב 1%', 'משקה שקדים או סויה לא ממותק', 'יוגורט טבעי מדולל בקצת מים']),
    (7,  array['שמן קנולה', 'חמאה מומסת']),
    (8,  array['ריקוטה', 'קוטג׳ 3%']),
    (9,  array['קוטג׳ נוסף', 'יוגורט יווני', 'סקיר או יוגורט חלבון']),
    (10, array['מוצרלה מגורדת', 'גבינה צהובה 9% (פחות שומן)', 'פרמזן (חצי מהכמות)']),
    (11, array['פטה', 'צפתית']),
    (12, array['זיתים', 'תירס', 'ברוקולי', 'פטריות', 'תרד', 'כל תוספת אחרת'])
  ) as v(pos, subs)
where i.recipe_id = r.id and r.title = 'פשטידת גבינות וחלבון' and i.position = v.pos;

