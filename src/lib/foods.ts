export const norm = (s: string) => s.toLowerCase().replace(/[״"]/g, '"').replace(/[׳']/g, "'").replace(/\s+/g, ' ').trim();
export const normKey = (s: string) => norm(s).replace(/["']/g, '');

const aliasRe = new Map<string, RegExp>();
function reFor(alias: string): RegExp {
  let re = aliasRe.get(alias);
  if (!re) {
    // Whole words only (optionally with a Hebrew prefix letter: "בקמח", "והשמן"), so "שום" does not match inside "שומשום".
    const escaped = normKey(alias).replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
    re = new RegExp(`(?:^|\\s)[ובהלמכש]{0,2}${escaped}(?=[\\s%.,)]|$)`);
    aliasRe.set(alias, re);
  }
  return re;
}

/** Longest alias found in the name wins ("קמח כוסמין לבן" beats "קמח"). */
export function findFood(name: string): Food | null {
  const n = normKey(name);
  let best: Food | null = null;
  let bestLen = 0;
  for (const f of FOODS) for (const a of f.aliases) {
    const k = normKey(a);
    if (k.length > bestLen && reFor(a).test(n)) { best = f; bestLen = k.length; }
  }
  return best;
}

/** Grams for qty+unit of this food, or null when the unit has no known weight (e.g. "יחידה" of an unknown food). */
export function gramsOf(food: Pick<Food, 'cup' | 'tbsp' | 'tsp' | 'unit' | 'can' | 'tub' | 'density'> | null, qty: number, unit: string): number | null {
  const d = food?.density ?? 1;
  switch (unit) {
    case 'גרם': return qty;
    case 'ק״ג': return qty * 1000;
    case 'מ״ל': return qty * d;
    case 'ליטר': return qty * 1000 * d;
    case 'כוס': return food?.cup != null ? qty * food.cup : qty * 240 * d;
    case 'כף': return food?.tbsp != null ? qty * food.tbsp : qty * 15 * d;
    case 'כפית': return food?.tsp != null ? qty * food.tsp : qty * 5 * d;
    case 'קורט': return qty * 0.5;
    case 'יחידה': return food?.unit != null ? qty * food.unit : food?.tub != null ? qty * food.tub : null; // a tub-type product: one unit = one tub
    case 'קופסה': return food?.can != null ? qty * food.can : null;
    case 'גביע': return food?.tub != null ? qty * food.tub : null;
    default: return null;
  }
}
