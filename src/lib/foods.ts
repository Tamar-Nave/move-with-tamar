export const MAX_AUTO_SUBS = 3;

export function subDefsFor(food: Food): SubDef[] {
  if (food.subs) return food.subs.slice(0, MAX_AUTO_SUBS);
  return (SUB_PICKS[food.key] ?? []).slice(0, MAX_AUTO_SUBS).map((k) => ({ name: FOODS.find((f) => f.key === k)?.subLabel ?? k, ratio: 1 }));
}

